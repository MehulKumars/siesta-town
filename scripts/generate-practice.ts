// Generates the practice towns: fifteen solver-verified towns in three tiers, always available beside
// the daily town. Run: node --experimental-strip-types scripts/generate-practice.ts
// It writes src/shared/practice.ts. Solutions are not written: the client never gets them.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { bandFor, generateTownReliably, townNames } from '../src/shared/engine/index.ts';
import type { NoonRule } from '../src/shared/engine/index.ts';

const noonRule: NoonRule = 'one';
/** The weekday whose difficulty band each practice town borrows (1 = Monday … 6 = Saturday, 0 = Sunday). */
const LADDER: { tier: 1 | 2 | 3; weekday: number }[] = [
  { tier: 1, weekday: 1 },
  { tier: 1, weekday: 1 },
  { tier: 1, weekday: 1 },
  { tier: 1, weekday: 2 },
  { tier: 1, weekday: 2 },
  { tier: 2, weekday: 3 },
  { tier: 2, weekday: 3 },
  { tier: 2, weekday: 4 },
  { tier: 2, weekday: 4 },
  { tier: 2, weekday: 4 },
  { tier: 3, weekday: 5 },
  { tier: 3, weekday: 5 },
  { tier: 3, weekday: 6 },
  { tier: 3, weekday: 6 },
  { tier: 3, weekday: 0 },
];

const names = townNames('siesta-practice-names-v1');
const towns = LADDER.map((step, index) => {
  const town = generateTownReliably(bandFor(step.weekday), `siesta:practice:v1:${index + 1}`, noonRule);
  console.log(`${index + 1}. tier ${step.tier}, ${town.puzzle.size}×${town.puzzle.size}, ${town.puzzle.heights.length} houses, ${town.solutions} solution(s), ${town.nodes} nodes`);
  return {
    id: `practice-${index + 1}`,
    tier: step.tier,
    title: names[index] ?? `Town ${index + 1}`,
    puzzle: town.puzzle,
  };
});

const file = fileURLToPath(new URL('../src/shared/practice.ts', import.meta.url));
writeFileSync(
  file,
  `// Generated by scripts/generate-practice.ts. Do not edit by hand: run the script again instead.
// Fifteen practice towns in three tiers, always there beside the daily town. No solutions in here.
import type { NoonRule, Puzzle } from './engine/types.ts';

export type PracticeTown = {
  id: string;
  /** 1 gentle, 2 steady, 3 tricky. */
  tier: 1 | 2 | 3;
  title: string;
  puzzle: Puzzle;
};

export const PRACTICE_NOON_RULE: NoonRule = '${noonRule}';

export const PRACTICE: readonly PracticeTown[] = ${JSON.stringify(towns, null, 2)};
`
);
console.log(`wrote ${towns.length} towns to ${file}`);
